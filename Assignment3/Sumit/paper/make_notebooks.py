def sub(s, old, new, count=1):
    n = s.count(old)
    assert n == count, f"patch expected {count}x, found {n}x: {old[:70]!r}"
    return s.replace(old, new)


def md(s):
    return {"cell_type": "markdown", "metadata": {}, "source": s.strip("\n").splitlines(True)}


def code(s):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": s.strip("\n").splitlines(True)}


def src(c):
    return "".join(c["source"])


def setsrc(c, s):
    c["source"] = s.splitlines(True)


def load(base):
    nb = json.load(open(os.path.join(EXP, base, base + ".ipynb")))
    nb["cells"] = [c for c in nb["cells"] if "Kaggle run log" not in src(c) and "output of the Kaggle run" not in src(c)]
    for c in nb["cells"]:
        if c["cell_type"] == "code":
            c["outputs"], c["execution_count"] = [], None
    return nb


def find(nb, needle):
    hits = [i for i, c in enumerate(nb["cells"]) if needle in src(c)]
    assert len(hits) == 1, (needle, hits)
    return hits[0]


