class Fade(nn.Module):
    """A layer being absorbed: its residual update is scaled by ALPHA (1 = original, 0 = removed)."""

    def __init__(self, inner):
        super().__init__()
        self.inner = inner

    def forward(self, h, *a, **k):
        return h if ALPHA["v"] == 0 else h + ALPHA["v"] * (self.inner(h, *a, **k) - h)


