def as_script(nb, name):
    """Code cells as one script (no shell magics), writing to its own data dir."""
    s = "\n\n".join("\n".join(l for l in src(c).splitlines() if not l.lstrip().startswith("!"))
                    for c in nb["cells"] if c["cell_type"] == "code")
    return sub(s, '"/kaggle/working/layer_merging" if os.path.exists("/kaggle/working")',
               f'"/kaggle/working/{name}/layer_merging" if os.path.exists("/kaggle/working")')


def pair_nb(names, smoke):
    pre = "s_" if smoke else ""
    srcs = {n: as_script(json.load(open(os.path.join(HERE, pre + n + ".ipynb"))), n) for n in names}
    meta = {"kernelspec": {"display_name": "Python 3", "name": "python3"}, "language_info": {"name": "python"}}
    return {"cells": [md(f"# Paired run: {' + '.join(names)} (one T4 each)\n\nGenerated by `paper/make_notebooks.py`."),
                      code(PAIR.replace("__SRC__", repr(srcs)))], "metadata": meta, "nbformat": 4, "nbformat_minor": 0}


