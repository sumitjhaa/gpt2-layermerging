"""Every measurement of every large-test run, in one Markdown file (results/all_metrics.md):
    python3 tools/make_metrics.py . > results/all_metrics.md
Per model: headline table (accuracy, skill kept above chance, perplexity, copying, speed), accuracy per benchmark,
accuracy per language, and perplexity per language (mC4 and Wikipedia)."""
import sys

import analyze as A

UNSEEN = ["ja", "ru"]


def acc_by(r, key):
    """mean accuracy % per benchmark (key=0) or per language (key=1), from the per-item hits"""
    d = {}
    for k, h in r["eval"]["hits"].items():
        d.setdefault(k.split("/")[key], []).append(100 * sum(map(int, h)) / len(h))
    return {g: sum(v) / len(v) for g, v in d.items()}


def skill_kept(r, o):
    """share of the original's above-chance accuracy that survives, averaged over benchmarks (0 % = guessing)"""
    a, b = acc_by(r, 0), acc_by(o, 0)
    ts = [t for t in A.TASKS if t in a]
    return sum((a[t] - A.CHANCE[t]) / (b[t] - A.CHANCE[t]) for t in ts) / len(ts) * 100


def main(root):
    print("# All measurements of the large test\n")
    print("Generated by `tools/make_metrics.py` from the run folders; every number below comes from the result JSONs.")
    print("What each measurement means: `docs/metrics_and_benchmarks.md`. Only the six training languages are used "
          "except in the unseen-language tables. Rows are sorted by layers removed, then method.\n")
    for model, R in A.load(root).items():
        o = R["original|0|—"]
        rows = sorted(R.values(), key=lambda r: (r["k"], r["method"] != "drop", A.name(r["method"])))
        print(f"## {model}\n")
        print("### Headline\n")
        print("| layers removed | method | params cut % | avg acc % (6 langs) | skill kept % | mC4 ppl +% | Wiki ppl +% "
              "| copy NLL | prefill tok/s | decode tok/s |")
        print("|---|---|---|---|---|---|---|---|---|---|")
        p0 = o["params"]
        for r in rows:
            sp = r["eval"].get("speed", {})
            acc = A.boot(A.cells(r, A.LANGS))[0]
            print(f"| {r['k']} | {A.name(r['method'])} | {100 * (1 - r['params'] / p0):.1f} | {acc:.1f} "
                  f"| {skill_kept(r, o):.0f} | {A.ppl_inc(r, o):+.1f} | {A.ppl_inc(r, o, 'wiki'):+.1f} "
                  f"| {r['eval']['copy_nll']:.3f} | {sp.get('prefill_tok_s', float('nan')):,.0f} "
                  f"| {sp.get('decode_tok_s', float('nan')):,.1f} |")
        print("\n### Accuracy per benchmark (%, mean over the six languages; chance in brackets)\n")
        print("| layers removed | method | " + " | ".join(f"{t} ({A.CHANCE[t]:.0f})" for t in A.TASKS) + " |")
        print("|---|---|" + "---|" * len(A.TASKS))
        for r in rows:
            c = {k: v for k, v in r["eval"]["hits"].items() if k.split("/")[1] in A.LANGS}
            a = acc_by({"eval": {"hits": c}}, 0)
            print(f"| {r['k']} | {A.name(r['method'])} | " + " | ".join(f"{a[t]:.1f}" if t in a else "—" for t in A.TASKS) + " |")
        print("\n### Accuracy per language (%, mean over the benchmarks; ja and ru were never used for training)\n")
        langs = A.LANGS + [l for l in UNSEEN if any(k.endswith("/" + l) for r in rows for k in r["eval"]["hits"])]
        print("| layers removed | method | " + " | ".join(langs) + " |")
        print("|---|---|" + "---|" * len(langs))
        for r in rows:
            a = acc_by(r, 1)
            print(f"| {r['k']} | {A.name(r['method'])} | " + " | ".join(f"{a[l]:.1f}" if l in a else "—" for l in langs) + " |")
        for ds, lab in (("mc4", "mC4"), ("wiki", "Wikipedia (Wiki-40B test)")):
            print(f"\n### {lab} perplexity per language (lower is better)\n")
            print("| layers removed | method | " + " | ".join(A.LANGS) + " |")
            print("|---|---|" + "---|" * len(A.LANGS))
            for r in rows:
                e = r["eval"][ds]
                print(f"| {r['k']} | {A.name(r['method'])} | " + " | ".join(f"{e[l]:.2f}" if l in e else "—" for l in A.LANGS) + " |")
        print()


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
