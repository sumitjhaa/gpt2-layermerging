FLOAT_UNION = ("        union = prism_layer(gid, nid).requires_grad_(True)\n",
               "        union = prism_layer(gid, nid).float().requires_grad_(True)  # fp32 master weights, also for an fp16 teacher\n")
SELFCHECK = ("\n_selfcheck()\n", "\nif CFG[\"teacher_dtype\"] == \"float32\":  # fp16 weights: the construction is checked on the fp32 model\n    _selfcheck()\n")


def build_nb(name, smoke):
    title, variant, cells = JOBS[name]
    if smoke:  # CPU smoke test: fp32 weights (CPU has no fp16 autocast)
        variant = dict(variant, teacher_dtype="float32")
    nb = patch_shared(load("13_shrink_icl"), variant, smoke)
    nb["cells"][0] = md(f"# {title}\n\nGenerated by `tools/make_notebooks.py` from `prism_shrink/prism_shrink_icl.ipynb` "
                        "(large test: 200-250 items per benchmark and language, per-item results, unseen languages ja / ru).")
    c = nb["cells"][find(nb, "def kd_train(")]
    setsrc(c, sub(sub(src(c), *KD_PATCH), "max(1, 1536 // x.shape[1])",
                  'max(1, CFG.get("mb_tokens", 1536) // x.shape[1])'))  # smaller micro-batches = same gradient, less memory
    c = nb["cells"][find(nb, "def shrink_build(")]
    s = src(c)
    for old, new in SHRINK_PATCHES + [FLOAT_UNION]:
        s = sub(s, old, new)
    setsrc(c, s)
    k = find(nb, "def shrink_build(")
    nb["cells"].insert(k + 1, code(NEWLIB))
    c = nb["cells"][find(nb, "def _selfcheck(")]
    setsrc(c, sub(src(c), *SELFCHECK))
    k = find(nb, "## Algorithm")
    nb["cells"] = nb["cells"][:k] + copy.deepcopy(cells)
    for c in nb["cells"]:  # fp16 weights (1.7B teacher): feed lm_head its own dtype; no-op for fp32 models
        if c["cell_type"] == "code" and "lm_head(" in src(c):
            setsrc(c, src(c).replace("model.lm_head(hc.float()).float()", "model.lm_head(hc.to(model.lm_head.weight.dtype)).float()")
                   .replace("model.lm_head(last.float())", "model.lm_head(last.to(model.lm_head.weight.dtype)).float()"))
    if smoke:
        nb["metadata"]["kaggle"] = {"accelerator": "none", "isInternetEnabled": True}
    return nb


def as_script(nb, name):
    '''Code cells as one script (no shell magics), writing to its own data dir.'''
    s = "\n\n".join("\n".join(l for l in src(c).splitlines() if not l.lstrip().startswith("!"))
                    for c in nb["cells"] if c["cell_type"] == "code")
    return sub(s, '"/kaggle/working/layer_merging" if os.path.exists("/kaggle/working")',
               f'"/kaggle/working/{name}/layer_merging" if os.path.exists("/kaggle/working")')


def pair_nb(names, smoke):
    srcs = {n: as_script(build_nb(n, smoke), n) for n in names}
    meta = {"kernelspec": {"display_name": "Python 3", "name": "python3"}, "language_info": {"name": "python"}}
    if smoke:
        meta["kaggle"] = {"accelerator": "none", "isInternetEnabled": True}
    return {"cells": [md(f"# Paired run: {' + '.join(names)} (one T4 each)\n\nGenerated by `tools/make_notebooks.py`."),
                      code(PAIR.replace("__SRC__", repr(srcs)))], "metadata": meta, "nbformat": 4, "nbformat_minor": 0}


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name in JOBS:
        json.dump(build_nb(name, False), open(os.path.join(OUT, name + ".ipynb"), "w"), indent=1, ensure_ascii=False)
    for pname, names in PAIRS.items():
        for smoke in (False, True):
            out = os.path.join(OUT, ("s_" if smoke else "") + pname + ".ipynb")
            json.dump(pair_nb(names, smoke), open(out, "w"), indent=1, ensure_ascii=False)
    print("written:", ", ".join(sorted(os.listdir(OUT))))
